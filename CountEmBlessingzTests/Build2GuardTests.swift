import Testing
import Foundation
import ImageIO
@testable import CountEmBlessingz

/// Things found in the submission audit (release/SUBMISSION_AUDIT.md) that must not come back.
struct Build2GuardTests {
    private var root: URL {
        URL(fileURLWithPath: #filePath).deletingLastPathComponent().deletingLastPathComponent()
    }

    private func text(_ path: String) throws -> String {
        try String(contentsOf: root.appending(path: path), encoding: .utf8)
    }

    // MARK: In the app

    /// Naming other people's films, shows or people in the UI is an intellectual-property flag in review.
    @Test func lookDescriptionsNameNoFilmsShowsOrPeople() {
        for theme in Themes.all {
            #expect(!theme.blurb.isEmpty, "\(theme.id) needs a description")
            for word in ["Crazy Rich Asians", "Anderson", "Succession"] {
                #expect(!theme.blurb.localizedCaseInsensitiveContains(word), "\(theme.id): \(theme.blurb)")
            }
        }
    }

    @Test func faceIDExplanationSaysWhatItIsFor() throws {
        let info = Bundle(for: AppSettings.self).infoDictionary ?? [:]
        let message = try #require(info["NSFaceIDUsageDescription"] as? String)
        #expect(message.contains("Face ID") && message.contains("private"), "\(message)")
        #expect(!message.localizedCaseInsensitiveContains("honeypot"), "the app's own jargon does not explain the purpose")
    }

    @Test func appBundleDeclaresItCollectsAndTracksNothing() throws {
        let url = try #require(Bundle(for: AppSettings.self).url(forResource: "PrivacyInfo", withExtension: "xcprivacy"))
        try expectEmptyManifest(at: url)
    }

    /// XcodeGen writes Info.plist from project.yml; a literal "1" there would ignore every build-number bump.
    @Test func appBuildNumberFollowsProjectYml() throws {
        let yml = try text("project.yml")
        let wanted = try #require(yml.components(separatedBy: "\n")
            .first { $0.contains("CURRENT_PROJECT_VERSION:") }?
            .split(separator: "\"").dropFirst().first.map(String.init))
        let info = Bundle(for: AppSettings.self).infoDictionary ?? [:]
        #expect(info["CFBundleVersion"] as? String == wanted, "bundle says \(String(describing: info["CFBundleVersion"])), project.yml says \(wanted)")
        #expect(info["CFBundleShortVersionString"] as? String == "1.0")
    }

    // MARK: In the widget (its files are not part of the test host, so read the sources)

    @Test func widgetDeclaresItCollectsAndTracksNothing() throws {
        try expectEmptyManifest(at: root.appending(path: "CountEmBlessingzWidget/PrivacyInfo.xcprivacy"))
    }

    /// A hard-coded "1" would stay behind when the app's build number goes up.
    @Test func widgetVersionFollowsTheAppVersion() throws {
        let plist = try text("CountEmBlessingzWidget/Info.plist")
        #expect(plist.contains("$(MARKETING_VERSION)") && plist.contains("$(CURRENT_PROJECT_VERSION)"))
    }

    /// With the goal optional, an unreadable store must not invent a 20,000 goal.
    @Test func widgetFallbackHasNoGoal() throws {
        let source = try text("CountEmBlessingzWidget/CountEmBlessingzWidget.swift")
        let fallback = try #require(source.components(separatedBy: "\n").first { $0.contains("PotEntry(date: .now, total: 0") })
        #expect(fallback.contains("goal: 0"), "\(fallback)")
    }

    // MARK: In the listing

    @Test func keywordsFitAndDoNotRepeatTheNameOrSubtitle() throws {
        let listing = try text("release/listing.md")
        let afterHeading = try #require(listing.components(separatedBy: "**Keywords**").last)
        let block = try #require(afterHeading.components(separatedBy: "```").dropFirst().first)
        let keywords = block.trimmingCharacters(in: .whitespacesAndNewlines)
        #expect(keywords.count <= 100, "\(keywords.count) characters")
        #expect(!keywords.contains(", ") && !keywords.contains(" ,"), "no spaces around commas")
        let indexedAlready = Set("count em blessingz your private angpao tracker".split(separator: " ").map(String.init))
        let words = keywords.lowercased().split(whereSeparator: { $0 == "," || $0 == " " }).map(String.init)
        #expect(words.filter(indexedAlready.contains).isEmpty, "already indexed from the name or subtitle: \(words.filter(indexedAlready.contains))")
        #expect(Set(words).count == words.count, "a word is repeated")
    }

    @Test func privacyPolicyMentionsTheSharingNameInSharedFiles() throws {
        #expect(try text("docs/privacy-policy.md").contains("sharing name"))
    }

    // MARK: Captioned screenshots (generated by release/caption-screenshots.swift)

    @Test(arguments: ["jade", "grand", "quiet"])
    func captionedScreenshotsAreStoreSizedAndOpaque(look: String) throws {
        let names = ["01-home", "02-insights", "03-import-review", "04-hall-of-fame", "05-add-blessing", "06-vibes"]
        for name in names {
            let url = root.appending(path: "release/screenshots-captioned/\(look)/\(name).png")
            let source = try #require(CGImageSourceCreateWithURL(url as CFURL, nil), "\(look)/\(name) is missing")
            let properties = try #require(CGImageSourceCopyPropertiesAtIndex(source, 0, nil) as? [CFString: Any])
            #expect(properties[kCGImagePropertyPixelWidth] as? Int == 1320, "\(look)/\(name) width")
            #expect(properties[kCGImagePropertyPixelHeight] as? Int == 2868, "\(look)/\(name) height")
            #expect(properties[kCGImagePropertyHasAlpha] as? Bool != true, "\(look)/\(name) must have no transparency")
        }
    }

    // MARK: Helpers

    private func expectEmptyManifest(at url: URL) throws {
        let data = try Data(contentsOf: url)
        let plist = try #require(PropertyListSerialization.propertyList(from: data, format: nil) as? [String: Any])
        #expect(plist["NSPrivacyTracking"] as? Bool == false)
        #expect((plist["NSPrivacyTrackingDomains"] as? [Any])?.isEmpty == true)
        #expect((plist["NSPrivacyCollectedDataTypes"] as? [Any])?.isEmpty == true)
        #expect((plist["NSPrivacyAccessedAPITypes"] as? [Any])?.isEmpty == true)
    }
}
